#!/usr/bin/env python3
"""
Generate sensor_stream.h for the Wokwi firmware: replays one TEST-split
scenario column (pressure, flow, vibration + nominal baseline) at the chosen
node, exactly as the dataset was generated (same code path, same noise draws).

Usage: python export_firmware_data.py --scenario 0 --node 3
"""
import argparse
import importlib.util
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
GEN = os.path.join(REPO, "04_Donnees", "generate_data.py")

spec = importlib.util.spec_from_file_location("gen", GEN)
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", type=int, default=None,
                    help="scenario id (default: pick a medium leak at --node in the test split)")
    ap.add_argument("--node", default="3")
    ap.add_argument("--out", default=os.path.join(REPO, "02_Code_Source", "edge", "sensor_stream.h"))
    args = ap.parse_args()

    inp = os.path.join(REPO, "04_Donnees", "Hanoi.inp")
    gen.init_worker(inp)
    patterns, scenarios = gen.make_manifest()
    by_id = {s["scenario_id"]: s for s in scenarios}

    if args.scenario is None:
        splits = pd.read_json(os.path.join(REPO, "04_Donnees", "generated", "splits.json"),
                              typ="series")
        test_ids = set(splits["test"])
        cands = [s for s in scenarios if s["scenario_id"] in test_ids
                 and s["kind"] == "leak" and s["leak_node"] == str(args.node)
                 and 0.03 < s["leak_frac"] < 0.07]
        if not cands:
            raise SystemExit(f"no medium leak scenario at node {args.node} in the test split")
        sc = cands[0]
    else:
        sc = by_id[args.scenario]

    print(f"scenario {sc['scenario_id']}: node={sc['leak_node']} "
          f"frac={sc['leak_frac']:.3f} start={sc['start_s']}")

    # re-run the scenario exactly like generate_data does
    pat = patterns[sc["pattern_id"]]
    rng = np.random.default_rng([gen.SEED, sc["scenario_id"]])
    wn0 = gen.build_wn(inp, pat["scale"], pat["jitter"], leak=None)
    r0 = gen.wntr.sim.WNTRSimulator(wn0).run_sim()
    p_nom = r0.node["pressure"][gen.JUNCTIONS].to_numpy()
    h_mean = p_nom.mean(axis=0)
    total_mean = float(r0.node["demand"][gen.JUNCTIONS].sum(axis=1).mean())

    vib = np.zeros_like(p_nom)
    leak_dem = np.zeros_like(p_nom)
    if sc["kind"] == "leak":
        li = gen.JUNCTIONS.index(sc["leak_node"])
        h = max(float(h_mean[li]), 0.5)
        area = sc["leak_frac"] * total_mean / (gen.CD * np.sqrt(2 * gen.G * h))
        wn = gen.build_wn(inp, pat["scale"], pat["jitter"],
                          leak=(sc["leak_node"], area, sc["start_s"]))
        res = gen.wntr.sim.WNTRSimulator(wn).run_sim()
        p = res.node["pressure"][gen.JUNCTIONS].to_numpy()
        q_node = gen.node_flow(res.link["flowrate"].to_numpy())
        leak_dem = res.node["leak_demand"][gen.JUNCTIONS].to_numpy()
        lf = np.maximum(leak_dem[:, li] * 1000.0, 0.0)
        vib[:, li] += gen.VIB_K * np.sqrt(lf)
    else:
        p = p_nom.copy()
        q_node = gen.node_flow(r0.link["flowrate"].to_numpy())

    p_meas = p + rng.normal(0, gen.SIGMA_P, p.shape)
    q_meas = q_node + rng.normal(0, 1.0, q_node.shape) * (gen.SIGMA_Q_REL * q_node + gen.SIGMA_Q_FLOOR)
    vib_meas = vib + rng.normal(0, gen.SIGMA_V, vib.shape)

    ni = gen.JUNCTIONS.index(str(args.node))
    P, Q, V, PN = p_meas[:, ni], q_meas[:, ni], vib_meas[:, ni], p_nom[:, ni]

    def arr(name, a):
        body = ",\n  ".join(",".join(f"{v:.5f}" for v in a[i:i+8])
                            for i in range(0, len(a), 8))
        return f"const float {name}[STREAM_N] PROGMEM = {{\n  {body}\n}};\n"

    with open(args.out, "w") as f:
        f.write("// Auto-generated by export_firmware_data.py - do not edit\n")
        f.write(f"// scenario {sc['scenario_id']} node {args.node} "
                f"(leak frac {sc['leak_frac']:.3f}, start {sc['start_s']}s)\n")
        f.write("#pragma once\n#include <Arduino.h>\n#define STREAM_N %d\n\n"
                % gen.N_STEPS)
        f.write(arr("P_STREAM", P))
        f.write(arr("Q_STREAM", Q))
        f.write(arr("VIB_STREAM", V))
        f.write(arr("PNOM_STREAM", PN))
    print(f"wrote {args.out} ({os.path.getsize(args.out)} bytes)")


if __name__ == "__main__":
    main()
